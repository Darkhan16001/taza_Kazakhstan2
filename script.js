function renderQuiz(index) {
  const q = questions[index];

  const hasAnswer =
    answers[index] !== undefined;

  const selected =
    hasAnswer ? answers[index].choice : null;

  const optionButtons = q.a.map((answer, i) => {
    let className = "option";

    if (hasAnswer) {
      if (i === q.correct) {
        className += " correct";
      } else if (i === selected) {
        className += " wrong";
      }
    }

    return `
      <button
        class="${className}"
        ${hasAnswer ? "disabled" : ""}
        onclick="chooseAnswer(${index}, ${i})"
      >
        ${String.fromCharCode(65 + i)}. ${answer}
      </button>
    `;
  }).join("");

  return `
    <section class="slide">
      <span class="section-label">
        ОЙЫН · ${index + 1}/15
      </span>

      <h1>🧠 ${index + 1}-сұрақ</h1>

      ${makeCard(
        "Сұрақ",
        `
          <p class="question">${q.q}</p>

          <div class="options">
            ${optionButtons}
          </div>

          ${
            hasAnswer
              ? `<p class="feedback">
                   ${selected === q.correct
                     ? "✅ Дұрыс жауап!"
                     : "❌ Қате жауап!"}
                 </p>`
              : ""
          }
        `
      )}

      ${makeCard(
        "Жауап беретін топ",
        `
          <p>
            Алдымен топты таңдаңдар,
            содан кейін жауапты басыңдар.
          </p>

          ${teamSelector()}
        `
      )}

      ${teamCards()}
    </section>
  `;
}

function chooseAnswer(index, choice) {
  if (answers[index] !== undefined) return;

  answers[index] = {
    choice: choice,
    team: selectedTeam
  };

  if (choice === questions[index].correct) {
    scores[selectedTeam]++;
  }

  render();
}

