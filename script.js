// =====================================
// БЕТТЕРДІ КӨРСЕТУ
// =====================================

function render() {
  const current = pages[page];

  switch (current.type) {
    case "home":
      app.innerHTML = renderHome();
      break;

    case "intro":
      app.innerHTML = renderIntro();
      break;

    case "topic":
      app.innerHTML = renderTopic(current.index);
      break;

    case "video":
      app.innerHTML = renderVideo();
      break;

    case "notes":
      app.innerHTML = renderNotes();
      break;

    case "teams":
      app.innerHTML = renderTeams();
      break;

    case "quiz":
      app.innerHTML = renderQuiz(current.index);
      break;

    case "discussion":
      app.innerHTML = renderDiscussion();
      break;

    case "results":
      app.innerHTML = renderResults();
      break;

    case "finish":
      app.innerHTML = renderFinish();
      break;
  }

  document.getElementById("pageNumber").textContent =
    `${page + 1} / ${pages.length}`;

  document.getElementById("backBtn").disabled =
    page === 0;

  const next = document.getElementById("nextBtn");

  next.disabled = page === pages.length - 1;

  next.textContent =
    page === 0 ? "Сабақты бастау →" : "Келесі →";
}

// =====================================
// НАВИГАЦИЯ
// =====================================

function nextPage() {
  if (page >= pages.length - 1) return;

  if (page === 0) {
    startTimer();
  }

  page++;
  render();
  window.scrollTo(0, 0);
}

function previousPage() {
  if (page <= 0) return;

  page--;
  render();
  window.scrollTo(0, 0);
}

